/**
 * Writes lib/judges/commits.generated.ts from `git log` so /judges can list
 * every commit with its Entire checkpoint page without needing `.git` at runtime.
 * An Entire link is the GitHub commit URL with `github.com` swapped for
 * `entire.io/gh`, so only the SHA and the `Entire-Checkpoint` trailer are stored.
 *
 * Usage: pnpm judges:commits (re-run after new commits are pushed)
 */

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const OUT = join(process.cwd(), "lib/judges/commits.generated.ts");
const FIELD = "\x1f";
const RECORD = "\x1e";

const raw = execFileSync(
  "git",
  [
    "log",
    "--reverse",
    `--format=%H${FIELD}%aI${FIELD}%s${FIELD}%(trailers:key=Entire-Checkpoint,valueonly,separator=%x2C)${FIELD}%b${RECORD}`,
  ],
  { encoding: "utf8" },
);

const commits = raw
  .split(RECORD)
  .map((r) => r.trim())
  .filter(Boolean)
  .map((r) => {
    const [sha, date, subject, checkpoint, body] = r.split(FIELD);
    return {
      sha,
      date,
      subject,
      checkpoint: checkpoint.trim() || null,
      neatlogs: /neatlogs/i.test(`${subject}\n${body}`),
    };
  });

writeFileSync(
  OUT,
  `// Generated by scripts/judgesCommits.ts — run \`pnpm judges:commits\`; do not edit.\n` +
    `import type { JudgeCommit } from "@/lib/judges/content";\n\n` +
    `export const COMMITS: JudgeCommit[] = ${JSON.stringify(commits, null, 2)};\n`,
);

console.log(`${commits.length} commits, ${commits.filter((c) => c.checkpoint).length} with checkpoints → ${OUT}`);
